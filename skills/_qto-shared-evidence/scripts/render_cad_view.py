SCHEMA = "qto-cad-drawing-view/1.0"
QUERY_FIELDS = {"question", "layout", "bounds", "layers", "background", "font_overrides"}
LIMITATIONS = [
    "derived_dxf_drawing_view: ezdxf重绘，不是AutoCAD原样显示或打印结果；不证明原DWG转换完整。",
    "仅二维俯视投影；视口、动态块、代理及自定义对象的实际显示仍受ezdxf支持范围限制。",
    "简单线型使用ACCURATE；复杂线型内的文字/形状不受支持。颜色按DXF及所选背景解析，不加载CTB/STB。",
    "文字以实际可用字体的字形路径绘制；替代字体、SHX/bigfont与复杂MTEXT可能改变字形和排版，须查看字体诊断。",
    "外部参照不自动加载；IMAGE只画边框，PDF/DGN/DWF底图、OLE和外部内容不能由此视图完整观察。",
    "每次完整读取DXF并遍历所选布局；有窗口时仅跳过经保守几何包络及整窗裕量证明远离窗口的简单图元，再裁剪。未知对象/文字/容器不据不完整包络跳过，不宣称空间增量解析或完整工程覆盖。",
    "画面像素及SVG路径不是测量依据；精确几何、源对象身份和编号定位仍使用同源索引及read_cad_scope。",
]


def _json_bound(path):
    data = Path(path).read_bytes()
    return json.loads(data.decode("utf-8-sig")), hashlib.sha256(data).hexdigest()


def _hash(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _dump(value):
    return json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False).encode("utf-8") + b"\n"


def _validate_query(query):
    if not isinstance(query, dict) or set(query) - QUERY_FIELDS:
        raise ValueError("query只接受question/layout/bounds/layers/background/font_overrides")
    if not isinstance(query.get("question"), str) or not query["question"].strip():
        raise ValueError("question必须说明本次要观察的问题")
    if "layout" in query and (not isinstance(query["layout"], str) or not query["layout"]):
        raise ValueError("layout必须是实际布局名称")
    bounds = query.get("bounds")
    if bounds is not None and (
        not isinstance(bounds, list) or len(bounds) != 4
        or any(isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) for v in bounds)
        or bounds[0] >= bounds[2] or bounds[1] >= bounds[3]
    ):
        raise ValueError("bounds须为有限且有面积的[xmin,ymin,xmax,ymax]原始坐标范围")
    layers = query.get("layers")
    if layers is not None and (
        not isinstance(layers, list) or not layers
        or any(not isinstance(v, str) or not v for v in layers)
        or len({v.casefold() for v in layers}) != len(layers)
    ):
        raise ValueError("layers须为不重复的非空图层名称数组；省略表示当前可见图层")
    if query.get("background", "default") not in {"default", "white", "black"}:
        raise ValueError("background须为default/white/black")
    overrides = query.get("font_overrides", {})
    if not isinstance(overrides, dict) or any(
        not isinstance(k, str) or not k or not isinstance(v, str) or not v or Path(v).name != v
        for k, v in overrides.items()
    ):
        raise ValueError("font_overrides须将实际文字样式映射到已安装字体文件名，不接受路径")
    _dump(query)


def _check_outputs(outputs, protected):
    seen = []
    protected = [Path(p).resolve() for p in protected]
    for path, suffix in outputs:
        path = Path(path)
        if path.suffix.lower() != suffix or path.is_symlink():
            raise ValueError(f"输出须为普通{suffix}文件，不接受符号链接")
        resolved = path.resolve()
        for other in protected + seen:
            if resolved == other or (path.exists() and other.exists() and os.path.samefile(path, other)):
                raise ValueError("输出不能覆盖来源、索引、查询、转换证据或另一输出")
        seen.append(resolved)


def _atomic_write(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".cad-view-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def _box_values(box):
    return [box.extmin.x, box.extmin.y, box.extmax.x, box.extmax.y] if box.has_data else None


def _inline_backend_styles(root):
    """Materialize this backend's simple CSS; MuPDF SVG ignores class rules.

    Otherwise text may appear black while every stroked line disappears from
    the PNG. Apply the same explicit attributes to the delivered SVG and PNG.
    This only accepts the simple class declarations generated by SVGBackend.
    """
    rules = {}
    for node in root.iter("{http://www.w3.org/2000/svg}style"):
        match = re.fullmatch(r"\s*\.([A-Za-z0-9_-]+)\s*\{([^{}]+)\}\s*", node.text or "")
        if not match:
            raise ValueError("绘图器生成了未支持的SVG样式，不能声称PNG与SVG画面一致")
        rules[match[1]] = dict(part.strip().split(":", 1) for part in match[2].split(";") if part.strip())
    for node in root.iter():
        for name in node.attrib.pop("class", "").split():
            if name not in rules:
                raise ValueError("绘图器SVG存在未解析样式")
            for key, value in rules[name].items():
                node.set(key.strip(), value.strip())


def _renderer(doc, query, source_sha256=None):
    try:
        from ezdxf.addons.drawing import Frontend, RenderContext
        from ezdxf.addons.drawing import config, svg
        from ezdxf.fonts import fonts
    except ImportError as exc:
        raise ValueError("DXF绘图需要ezdxf==1.4.4及Pillow；请安装后重试") from exc

    # A stale on-disk ezdxf cache can miss installed CJK fonts. Discover actual
    # declared/requested fonts in the standard font directories; do not change
    # the requested font or persist a new cache as part of viewing a drawing.
    fonts.load()
    requested_fonts = [style.dxf.get("font", "") for style in doc.styles]
    requested_fonts += list(query.get("font_overrides", {}).values())
    refresh_fonts = any(name and not fonts.font_manager.has_font(name) for name in requested_fonts)
    if refresh_fonts:
        fonts.font_manager.build(support_dirs=False)
    ctx = RenderContext(doc)
    # Public cache serialization supplies the actual runtime font file, rather
    # than guessing a path from the style name. This is environment evidence,
    # not a new project input or a change to the source's font declaration.
    font_paths = {Path(row[0]).name.casefold(): Path(row[0])
                  for row in json.loads(fonts.font_manager.dumps()).get("font-faces", [])}
    selected = {name.casefold() for name in query.get("layers", [])} or None
    known = {layer.dxf.name.casefold() for layer in doc.layers}
    if selected and selected - known:
        raise ValueError(f"图层不存在: {sorted(selected - known)}")

    def select_layers(layers):
        for layer in layers:
            if selected is not None and layer.layer.casefold() not in selected:
                layer.is_visible = False

    ctx.set_layer_properties_override(select_layers)
    overrides = {name.casefold(): font for name, font in query.get("font_overrides", {}).items()}
    if set(overrides) - set(ctx.fonts):
        raise ValueError("font_overrides含不存在的文字样式")
    for name, filename in overrides.items():
        if not fonts.font_manager.has_font(filename):
            raise ValueError(f"字体未安装或未被ezdxf字体缓存发现: {filename}")
        ctx.fonts[name] = fonts.find_font_face(filename)

    class ObservedFrontend(Frontend):
        def __init__(self, *args, **kwargs):
            self.messages = []
            self.skipped = []
            self.encountered = Counter()
            self.font_observations = {}
            self.display_issues = []
            self.window_culled = Counter()
            super().__init__(*args, **kwargs)

        def log_message(self, message):
            self.messages.append(str(message))

        def skip_entity(self, entity, msg):
            self.skipped.append({"handle": entity.dxf.get("handle"), "entity_type": entity.dxftype(),
                                 "reason": str(msg)})

        def draw_hatch_pattern(self, polygon, paths, properties):
            # The native frontend uses random origin jitter. Use the same
            # native hatching/OCS pipeline with a source-bound small jitter;
            # culling far hatches must not change visible pattern origins.
            from ezdxf.render import hatching
            if not polygon.pattern or not polygon.pattern.lines:
                return
            ocs=polygon.ocs();elevation=polygon.dxf.elevation.z
            properties.linetype_pattern=tuple();lines=[]
            started=time.perf_counter();maximum=self.config.hatching_timeout
            def timeout():
                if time.perf_counter()-started>maximum:
                    self.log_message(f'hatching timeout of {maximum}s reached for {polygon} - aborting')
                    return True
                return False
            for baseline in deterministic_pattern_baselines(polygon,self.config.min_hatch_line_distance,source_sha256):
                for line in hatching.hatch_paths(baseline,paths,timeout):
                    for start,end in baseline.pattern_renderer(line.distance).render(line.start,line.end):
                        if ocs.transform:
                            start,end=ocs.to_wcs((start.x,start.y,elevation)),ocs.to_wcs((end.x,end.y,elevation))
                        lines.append((start,end))
            self.pipeline.draw_solid_lines(lines,properties)

        def draw_entity(self, entity, properties):
            kind = entity.dxftype()
            self.encountered[kind] += 1
            handle = entity.dxf.get("handle")
            if kind in {"IMAGE", "OLE2FRAME", "PDFUNDERLAY", "DGNUNDERLAY", "DWFUNDERLAY"}:
                self.display_issues.append({"handle": handle, "entity_type": kind,
                    "reason": "外部/嵌入内容未读取；若有边框也不代表已显示内容"})
            if kind in {"XLINE", "RAY"}:
                self.display_issues.append({"handle": handle, "entity_type": kind,
                    "reason": "无限构造线采用渲染器有限显示长度，显示端点不是原图边界",
                    "display_length_raw": self.config.infinite_line_length})
            if kind == "INSERT":
                block = doc.blocks.get(entity.dxf.name)
                if block and block.block.is_xref:
                    self.display_issues.append({"handle": handle, "entity_type": kind,
                        "reason": "外部参照未加载", "block_name": entity.dxf.name})
                if entity.dxf.name.startswith("*U"):
                    self.display_issues.append({"handle": handle, "entity_type": kind,
                        "reason": "匿名块可能关联动态状态，不能证明与原生CAD当前可见状态一致"})
            if entity.proxy_graphic:
                self.display_issues.append({"handle": handle, "entity_type": kind,
                    "reason": "存在代理图形；仅作图样观察，不解释自定义对象语义"})
            if kind in {"TEXT", "MTEXT", "ATTRIB", "ATTDEF"}:
                style = entity.dxf.get("style", "Standard")
                face = self.get_font_face(properties)
                actual = self.text_engine.get_font(face).name
                definition = doc.styles.get(style)
                requested = definition.dxf.get("font", "") if definition else ""
                key = (style, actual)
                record = self.font_observations.setdefault(key, {
                    "style": style, "declared_font": requested, "resolved_font": actual,
                    "explicit_override": overrides.get(style.casefold()),
                    "font_substitution": bool(requested) and Path(requested).name.casefold() != actual.casefold(),
                    "bigfont": definition.dxf.get("bigfont", "") if definition else "",
                    "text_entity_count": 0, "missing_codepoints": set(),
                    "glyph_check": "unverified_for_stroke_or_complex_inline_fonts"})
                record["text_entity_count"] += 1
                if "runtime_font_file" not in record:
                    path = font_paths.get(actual.casefold())
                    record["runtime_font_file"] = {"path": str(path.resolve()), "sha256": _hash(path)} if path and path.is_file() else None
                text = entity.plain_text() if hasattr(entity, "plain_text") else entity.dxf.get("text", "")
                if Path(actual).suffix.lower() in {".ttf", ".otf", ".ttc"}:
                    cmap = fonts.font_manager.get_ttf_font(actual).getBestCmap() or {}
                    record["glyph_check"] = "base_font_cmap_only; inline_font_overrides_not_fully_checked"
                    record["missing_codepoints"].update(ord(c) for c in text if not c.isspace() and ord(c) not in cmap)
            marker_size=self.config.pdsize
            if self.config.pdmode == 0 or properties.layer.lower() == 'defpoints':
                marker_size=0
            if proven_far_outside(entity, query.get('bounds'), properties, marker_size):
                self.window_culled[kind] += 1
                return
            return super().draw_entity(entity, properties)

    cfg = config.Configuration(
        line_policy=config.LinePolicy.ACCURATE,
        color_policy=config.ColorPolicy.COLOR,
        background_policy={"default": config.BackgroundPolicy.DEFAULT,
                           "white": config.BackgroundPolicy.WHITE,
                           "black": config.BackgroundPolicy.BLACK}[query.get("background", "default")],
        text_policy=config.TextPolicy.FILLING, hatch_policy=config.HatchPolicy.NORMAL,
        image_policy=config.ImagePolicy.RECT, proxy_graphic_policy=config.ProxyGraphicPolicy.SHOW,
    )
    backend = svg.SVGBackend()
    frontend = ObservedFrontend(ctx, backend, config=cfg)
    frontend.font_cache_refreshed = refresh_fonts
    return frontend, backend


def render_view(source, query, *, svg_path, png_path=None, output_path=None,
                pixels=1600, index=None, input_paths=(), expected_input_hashes=None):
    """Write a derived DXF view and return its provenance/limitations metadata.

    ``source`` uses the workbench source JSON (optional authoritative_source).
    An optional existing ``index`` is verified and referenced, never required to
    interpret or select objects. ``input_paths`` protects CLI JSON inputs.
    ``expected_input_hashes`` binds parsed JSON arguments to the exact bytes the
    caller read; the CLI always supplies it. ``bounds`` are raw layout units.
    """
    _validate_query(query)
    if isinstance(pixels, bool) or not isinstance(pixels, int) or not 256 <= pixels <= 4096:
        raise ValueError("pixels须为256至4096的整数，指定PNG最长边")
    if not isinstance(source, dict):
        raise ValueError("source须为包含path/sha256的来源描述")
    source = copy.deepcopy(source)
    authoritative = source.pop("authoritative_source", None) or copy.deepcopy(source)
    verify_source_file(source, "DXF来源")
    verify_source_file(authoritative, "权威来源")
    if Path(source["path"]).suffix.lower() != ".dxf":
        raise ValueError("图样入口需要DXF；DWG须先通过既有转换流程")
    if index is not None:
        workbench._verified_index(index)
        for expected, actual in ((index["source"], source), (index["authoritative_source"], authoritative)):
            if Path(expected["path"]).resolve() != Path(actual["path"]).resolve() or expected["sha256"].lower() != actual["sha256"].lower():
                raise ValueError("索引与图样来源不一致")
    sidecar = Path(str(source["path"]) + ".export.json")
    protected = [Path(source["path"]), Path(authoritative["path"]), sidecar, *map(Path, input_paths)]
    inputs_before = {str(p.resolve()): _hash(p) for p in protected if p.is_file()}
    for declared in (source, authoritative):
        if inputs_before[str(Path(declared["path"]).resolve())] != str(declared["sha256"]).lower():
            raise ValueError("来源在声明校验与读取之间已改变，不发布旧身份的图样")
    for path, digest in (expected_input_hashes or {}).items():
        if inputs_before.get(str(Path(path).resolve())) != str(digest).lower():
            raise ValueError("输入JSON文件与实际解析字节已不一致，不发布图样")
    outputs = [(Path(svg_path), ".svg")]
    if png_path is not None:
        outputs.append((Path(png_path), ".png"))
    if output_path is not None:
        outputs.append((Path(output_path), ".json"))
    _check_outputs(outputs, protected)

    try:
        from ezdxf.addons.drawing import layout
    except ImportError as exc:
        raise ValueError("DXF绘图需要ezdxf==1.4.4及Pillow；请安装后重试") from exc
    from ezdxf.math import BoundingBox2d
    import ezdxf
    doc, read_diagnostics = read_dxf_with_diagnostics(source["path"])
    layout_name = query.get("layout", index["layout"] if index else "Model")
    if layout_name not in doc.layouts:
        raise ValueError(f"布局不存在: {layout_name}；可用布局: {list(doc.layout_names())}")
    drawing_messages = io.StringIO()
    with contextlib.redirect_stdout(drawing_messages):
        frontend, backend = _renderer(doc, query, source['sha256'])
        frontend.draw_layout(doc.layouts.get(layout_name))
    drawn_box = backend.player().bbox()
    bounds = query.get("bounds")
    if bounds is None:
        if not drawn_box.has_data:
            raise ValueError("所选布局/图层没有可绘内容；指定实际bounds可查看空窗及诊断")
        bounds = _box_values(drawn_box)
        # A lone horizontal/vertical line still requires a visible, finite view.
        pad = max(bounds[2] - bounds[0], bounds[3] - bounds[1], 1.0) * 0.02
        bounds = [bounds[0] - pad, bounds[1] - pad, bounds[2] + pad, bounds[3] + pad]
    box = BoundingBox2d([bounds[:2], bounds[2:]])
    width, height = box.size
    if not all(math.isfinite(v) and v > 0 for v in (width, height)):
        raise ValueError("绘图范围过大或没有有限面积")
    # Clip in source coordinates too: rounded SVG page dimensions can otherwise
    # expose a sliver beyond the requested window on one side.
    clipped = backend.player()
    clipped.crop_rect(box.extmin, box.extmax, max(width, height) / 1_000_000)
    backend.records = clipped.records
    # A fixed display page preserves aspect and avoids treating raw units as mm.
    if width >= height:
        page_width, page_height = 297.0, max(0.1, 297.0 * height / width)
    else:
        page_width, page_height = max(0.1, 297.0 * width / height), 297.0
    svg_text = backend.get_string(layout.Page(page_width, page_height),
        settings=layout.Settings(crop_at_margins=True), render_box=box)
    if not backend.transformation_matrix:
        raise ValueError("绘图器未生成有效画面变换")
    root = ET.fromstring(svg_text)
    _inline_backend_styles(root)
    metadata_tag = ET.SubElement(root, "{http://www.w3.org/2000/svg}metadata")
    metadata_tag.text = json.dumps({"kind": "derived_dxf_drawing_view", "source_sha256": source["sha256"],
                                  "layout": layout_name, "bounds_raw": bounds}, ensure_ascii=False)
    svg_data = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    png_data = None
    png_dimensions = None
    if png_path is not None:
        try:
            import pymupdf
        except ImportError as exc:
            raise ValueError("PNG观察图需要PyMuPDF：pip install PyMuPDF；SVG不依赖此包") from exc
        with pymupdf.open(stream=svg_data, filetype="svg") as rendered:
            page = rendered[0]
            scale = pixels / max(page.rect.width, page.rect.height)
            pixmap = page.get_pixmap(matrix=pymupdf.Matrix(scale, scale), alpha=False)
            png_data = pixmap.tobytes("png")
            png_dimensions = [pixmap.width, pixmap.height]

    font_records = []
    for record in frontend.font_observations.values():
        row = dict(record)
        row["missing_codepoints"] = [f"U+{n:04X}" for n in sorted(row["missing_codepoints"])]
        font_records.append(row)
    complex_types = [item.dxf.name for item in doc.linetypes if item.pattern_tags.is_complex_type()]
    issues = frontend.display_issues
    if complex_types:
        issues.append({"reason": "源文件含复杂线型，文字/形状部分不受支持；存在不代表本窗口实际使用",
                       "linetypes": complex_types})
    converted = Path(source["path"]).resolve() != Path(authoritative["path"]).resolve()
    report = {
        "schema_version": SCHEMA, "kind": "derived_dxf_drawing_view", "answer_status": "observation_only_model_interpretation_required",
        "question": query["question"], "query": copy.deepcopy(query),
        "source": source, "authoritative_source": authoritative,
        "index_sha256": index["index_sha256"] if index else None,
        "index_layout": index["layout"] if index else None,
        "index_scope": index.get("index_scope") if index else None,
        "layout": layout_name, "available_layouts": list(doc.layout_names()),
        "bounds_raw": list(bounds), "bounds_basis": "explicit_query" if query.get("bounds") is not None else "rendered_extents_plus_2_percent",
        "drawn_bounds_before_crop_raw": _box_values(drawn_box),
        "raw_unit": workbench.UNITS.get(int(doc.header.get("$INSUNITS", 0)), "Unknown"),
        "layers": [{"name": layer.dxf.name, "off": layer.is_off(), "frozen": layer.is_frozen(),
                    "selected": not query.get("layers") or layer.dxf.name.casefold() in {v.casefold() for v in query["layers"]}}
                   for layer in doc.layers],
        "renderer": {"name": "ezdxf.drawing.SVGBackend", "ezdxf_version": ezdxf.__version__,
                     "background": query.get("background", "default"), "line_policy": "ACCURATE", "text_policy": "glyph_paths",
                     "external_images": "frames_only_not_loaded", "coordinate_transform_dxf_to_svg": list(backend.transformation_matrix),
                     "hatch_pattern_origin_jitter": "source_bound_sha256_small_jitter/1.0; native range preserved; display only; original pattern definitions not rewritten",
                     "font_cache_refreshed_from_installed_fonts": frontend.font_cache_refreshed,
                     "svg_viewbox": root.attrib.get("viewBox"), "png_pixels": png_dimensions},
        "diagnostics_scope": "selected_layout_rendering_before_window_crop; counts_are_not_physical_objects_or_selected_window_inventory",
        "window_render_filter": {
            "enabled": query.get('bounds') is not None,
            "culled_by_type": dict(frontend.window_culled),
            "culled_count": sum(frontend.window_culled.values()),
            "padding_raw": max(bounds[2]-bounds[0], bounds[3]-bounds[1]) if query.get('bounds') is not None else None,
            "resolved_point_marker_size_raw": frontend.config.pdsize,
            "resolved_point_marker_mode": frontend.config.pdmode,
            "meaning": "display-only conservative culling; full source/layout traversal retained; unknown geometry, annotations and containers are not culled; drawn_bounds_before_crop_raw covers retained drawn records, not all source extents"
        },
        "encountered_entity_types": dict(frontend.encountered), "skipped_entities": frontend.skipped,
        "display_issues": issues, "font_observations": font_records,
        "renderer_messages": frontend.messages + drawing_messages.getvalue().splitlines(),
        "source_read_diagnostics": read_diagnostics,
        "conversion": {"different_authoritative_file": converted, "export_record": str(sidecar.resolve()) if sidecar.is_file() else None,
                       "export_record_validity": "not_validated_by_renderer", "warnings": index.get("conversion_warnings", []) if index else []},
        "input_file_hashes": inputs_before, "limitations": LIMITATIONS,
        "artifacts": {"drawing_svg": {"path": str(Path(svg_path).resolve()), "sha256": hashlib.sha256(svg_data).hexdigest()},
                      "drawing_png": {"path": str(Path(png_path).resolve()), "sha256": hashlib.sha256(png_data).hexdigest()} if png_data else None},
        "object_numbering": "not_in_this_view; use_same_source_index_and_read_cad_scope_for_locator_and_exact_facts",
    }
    # A changed drawing or query must not publish a view attributed to old bytes.
    for path, digest in inputs_before.items():
        verify_source_file({"path": path, "sha256": digest}, "绘图输入")
    verify_source_file(source, "DXF来源声明")
    verify_source_file(authoritative, "权威来源声明")
    for row in font_records:
        if row["runtime_font_file"]:
            verify_source_file(row["runtime_font_file"], "运行环境字体")
            protected.append(Path(row["runtime_font_file"]["path"]))
    _check_outputs(outputs, protected)
    _atomic_write(svg_path, svg_data)
    if png_data is not None:
        _atomic_write(png_path, png_data)
    if output_path is not None:
        _atomic_write(output_path, _dump(report))
    return report


def main():
    parser = argparse.ArgumentParser(description="供模型观察的来源绑定DXF图样；不作工程分类")
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument("--source", type=Path)
    inputs.add_argument("--index", type=Path)
    parser.add_argument("--query", type=Path, required=True)
    parser.add_argument("--svg", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--png", type=Path)
    parser.add_argument("--pixels", type=int, default=1600)
    args = parser.parse_args()
    try:
        descriptor_path = args.index or args.source
        descriptor, descriptor_hash = _json_bound(descriptor_path)
        query, query_hash = _json_bound(args.query)
        index = descriptor if args.index else None
        source = dict(index["source"], authoritative_source=index["authoritative_source"]) if index else descriptor
        report = render_view(source, query, svg_path=args.svg, png_path=args.png,
            output_path=args.output, pixels=args.pixels, index=index,
            input_paths=[args.query, descriptor_path],
            expected_input_hashes={str(descriptor_path): descriptor_hash, str(args.query): query_hash})
        print(json.dumps({"status": "RENDERED", "kind": report["kind"], "output": str(args.output),
                          "artifacts": report["artifacts"], "display_issue_count": len(report["display_issues"]),
                          "skipped_count": len(report["skipped_entities"]),
                          "font_substitution_count": sum(row["font_substitution"] for row in report["font_observations"])}, ensure_ascii=False))
        return 0
    except (ValueError, OSError, KeyError, TypeError, ImportError, RuntimeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
