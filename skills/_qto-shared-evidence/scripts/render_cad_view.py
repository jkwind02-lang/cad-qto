"""Source-bound DXF drawing views for model observation, without classification.

The ezdxf drawing frontend resolves display properties and text glyph geometry.
Its derived view is separate from the workbench's numbered object locator and
from the exact CAD facts used for measurements. No source drawing is rewritten.
"""
